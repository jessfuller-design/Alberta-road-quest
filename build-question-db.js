const fs = require('fs');
const path = require('path');

const root = __dirname;
const masterPath = path.join(root, 'questions.json');
const master = JSON.parse(fs.readFileSync(masterPath, 'utf8'));
const byId = new Map(master.map(question => [question.id, question]));
const packFiles = fs.readdirSync(root)
  .filter(name => /^pack-\d+.*\.json$/.test(name))
  .sort();

for (const name of packFiles) {
  const pack = JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));
  if (!Array.isArray(pack)) throw new Error(`${name} must contain a JSON array`);
  for (const question of pack) {
    const existing = byId.get(question.id);
    if (existing && JSON.stringify(existing) !== JSON.stringify(question)) {
      throw new Error(`${name}: ID ${question.id} conflicts with the master database`);
    }
    if (!existing) byId.set(question.id, question);
  }
}

const questions = [...byId.values()].sort((a, b) => a.id - b.id);
fs.writeFileSync(masterPath, `${JSON.stringify(questions, null, 2)}\n`);

const helpers = `\n\nwindow.RoadQuestDB = {\n` +
  `  all() { return window.ROADQUEST_QUESTIONS.slice(); },\n` +
  `  categories() { return [...new Set(window.ROADQUEST_QUESTIONS.map(q => q.cat))]; },\n` +
  `  byCategory(category) { return window.ROADQUEST_QUESTIONS.filter(q => q.cat === category); },\n` +
  `  byId(id) { return window.ROADQUEST_QUESTIONS.find(q => q.id === Number(id)); },\n` +
  `  byChapter(chapter) { return window.ROADQUEST_QUESTIONS.filter(q => q.chapter === Number(chapter)); },\n` +
  `  byDifficulty(level) { return window.ROADQUEST_QUESTIONS.filter(q => q.difficulty === Number(level)); },\n` +
  `  search(term) { const t=String(term||'').toLowerCase(); return window.ROADQUEST_QUESTIONS.filter(q => [q.q,q.why,q.cat,q.section,...(q.a||[]),...(q.tags||[])].filter(Boolean).join(' ').toLowerCase().includes(t)); },\n` +
  `  random(count=20, category=null) { const pool=category ? this.byCategory(category) : this.all(); return pool.sort(() => Math.random() - 0.5).slice(0, count); }\n` +
  `};\n`;
const js = `// Generated by build-question-db.js. Do not edit manually.\n` +
  `window.ROADQUEST_QUESTIONS = ${JSON.stringify(questions)};` + helpers;
fs.writeFileSync(path.join(root, 'questions.js'), js);

console.log(`Built ${questions.length} questions using ${packFiles.length} pack files.`);
